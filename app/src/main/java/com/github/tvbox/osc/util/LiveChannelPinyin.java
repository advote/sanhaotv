    /** 取单个汉字的首字母，非汉字或无读音返回 '#'。 */
    private static char initialOf(char c) {
        if (c < CJK_BASE || c > CJK_END) return '#';
        int index = c - CJK_BASE;
        if (index < 0 || index >= INITIALS.length()) return '#';
        return INITIALS.charAt(index);
    }

    /**
     * 把频道名转成用于搜索的大写索引串：汉字取首字母，英文字母转大写，数字保留，
     * 其余符号忽略。例：「CCTV1 综合」-> CCTV1ZH，「湖南卫视」-> HNWS。
     */
    public static String initialsOf(String text) {
        if (text == null || text.length() == 0) return "";
        StringBuilder sb = new StringBuilder(text.length());
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (c >= CJK_BASE && c <= CJK_END) {
                char p = initialOf(c);
                if (p >= 'A' && p <= 'Z') sb.append(p);
            } else if (c >= 'A' && c <= 'Z') {
                sb.append(c);
            } else if (c >= 'a' && c <= 'z') {
                sb.append((char) (c - 32));
            } else if (c >= '0' && c <= '9') {
                sb.append(c);
            }
        }
        return sb.toString();
    }

    /** 只保留大写字母和数字，用于拼音/英文关键字归一化。 */
    private static String normalize(String keyword) {
        if (keyword == null) return "";
        StringBuilder sb = new StringBuilder(keyword.length());
        for (int i = 0; i < keyword.length(); i++) {
            char c = keyword.charAt(i);
            if (c >= 'A' && c <= 'Z') sb.append(c);
            else if (c >= 'a' && c <= 'z') sb.append((char) (c - 32));
            else if (c >= '0' && c <= '9') sb.append(c);
        }
        return sb.toString();
    }

    /** 频道名索引串是否包含关键字（hn -> HNWS，cc -> CCTV1ZH）。 */
    public static boolean matches(String channelName, String keyword) {
        if (channelName == null || keyword == null) return false;
        String key = normalize(keyword);
        if (key.length() == 0) return false;
        return initialsOf(channelName).contains(key);
    }

